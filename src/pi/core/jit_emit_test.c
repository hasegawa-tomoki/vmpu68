/* jit_emit_test.c: エンコーダの検証。各行 "アセンブリ ; 生成ワード" を出力し、
 * 別途 as で組み立てた期待値と比較する(tools/jit_emit_check.sh)。 */
#include <stdio.h>
#include "jit_a64_emit.h"
static uint32_t buf[4096];
static a64_t E = { buf, 0, 4096, 0 };
#define T(asmtext, call) do { uint32_t n0 = E.n; call; printf("%s\t", asmtext); for (uint32_t i = n0; i < E.n; i++) printf("%08x ", E.buf[i]); printf("\n"); } while (0)
int main(void)
{
    T("ldr w1, [x19, #64]",        a64_ldr_w(&E, 1, 19, 64));
    T("str w2, [x19, #100]",       a64_str_w(&E, 2, 19, 100));
    T("ldr x3, [x24, #16]",        a64_ldr_x(&E, 3, 24, 16));
    T("str x4, [x19, #8]",         a64_str_x(&E, 4, 19, 8));
    T("ldrh w5, [x20, #6]",        a64_ldrh_w(&E, 5, 20, 6));
    T("strh w6, [x20, #8]",        a64_strh_w(&E, 6, 20, 8));
    T("ldrb w7, [x20, #3]",        a64_ldrb_w(&E, 7, 20, 3));
    T("strb w8, [x20, #1]",        a64_strb_w(&E, 8, 20, 1));
    T("ldrsh w9, [x20, #2]",       a64_ldrsh_w(&E, 9, 20, 2));
    T("ldrsb w10, [x20, #1]",      a64_ldrsb_w(&E, 10, 20, 1));
    T("ldr w1, [x20, x0]",         a64_ldr_w_r(&E, 1, 20, 0));
    T("str w1, [x20, x0]",         a64_str_w_r(&E, 1, 20, 0));
    T("ldrh w1, [x20, x0]",        a64_ldrh_w_r(&E, 1, 20, 0));
    T("strh w1, [x20, x0]",        a64_strh_w_r(&E, 1, 20, 0));
    T("ldrb w1, [x20, x0]",        a64_ldrb_w_r(&E, 1, 20, 0));
    T("strb w1, [x20, x0]",        a64_strb_w_r(&E, 1, 20, 0));
    T("stp x29, x30, [sp, #-16]!", a64_stp_pre(&E, 29, 30, SP, -16));
    T("ldp x29, x30, [sp], #16",   a64_ldp_post(&E, 29, 30, SP, 16));
    T("stp x19, x20, [sp, #16]",   a64_stp_off(&E, 19, 20, SP, 16));
    T("ldp x21, x22, [sp, #32]",   a64_ldp_off(&E, 21, 22, SP, 32));
    T("movz w1, #0x1234",          a64_movz_w(&E, 1, 0x1234, 0));
    T("movk w1, #0x5678, lsl #16", a64_movk_w(&E, 1, 0x5678, 1));
    T("movn w2, #0x10",            a64_movn_w(&E, 2, 0x10, 0));
    T("movz x3, #0x8000, lsl #32", a64_movz_x(&E, 3, 0x8000, 2));
    T("movk x3, #0x1, lsl #48",    a64_movk_x(&E, 3, 1, 3));
    T("add w1, w2, w3",            a64_add_w(&E, 1, 2, 3));
    T("adds w1, w2, w3",           a64_adds_w(&E, 1, 2, 3));
    T("sub w1, w2, w3",            a64_sub_w(&E, 1, 2, 3));
    T("subs w1, w2, w3",           a64_subs_w(&E, 1, 2, 3));
    T("add x1, x2, x3",            a64_add_x(&E, 1, 2, 3));
    T("and w1, w2, w3",            a64_and_w(&E, 1, 2, 3));
    T("ands w1, w2, w3",           a64_ands_w(&E, 1, 2, 3));
    T("orr w1, w2, w3",            a64_orr_w(&E, 1, 2, 3));
    T("eor w1, w2, w3",            a64_eor_w(&E, 1, 2, 3));
    T("orn w1, w2, w3",            a64_orn_w(&E, 1, 2, 3));
    T("mov w1, w2",                a64_mov_w(&E, 1, 2));
    T("mvn w1, w2",                a64_mvn_w(&E, 1, 2));
    T("neg w1, w2",                a64_neg_w(&E, 1, 2));
    T("negs w1, w2",               a64_negs_w(&E, 1, 2));
    T("cmp w1, w2",                a64_cmp_w(&E, 1, 2));
    T("tst w1, w2",                a64_tst_w(&E, 1, 2));
    T("add w1, w2, #100",          a64_add_w_imm(&E, 1, 2, 100));
    T("adds w1, w2, #7",           a64_adds_w_imm(&E, 1, 2, 7));
    T("sub w1, w2, #100",          a64_sub_w_imm(&E, 1, 2, 100));
    T("subs w1, w2, #7",           a64_subs_w_imm(&E, 1, 2, 7));
    T("add x1, x2, #100",          a64_add_x_imm(&E, 1, 2, 100));
    T("sub x1, x2, #8",            a64_sub_x_imm(&E, 1, 2, 8));
    T("cmp w1, #5",                a64_cmp_w_imm(&E, 1, 5));
    T("and w1, w2, #0xff",         a64_and_w_ff(&E, 1, 2));
    T("and w1, w2, #0xffff",       a64_and_w_ffff(&E, 1, 2));
    T("and w1, w2, #0x80",         a64_and_w_80(&E, 1, 2));
    T("and w1, w2, #0x100",        a64_and_w_100(&E, 1, 2));
    T("orr w1, w2, #0x80",         a64_orr_w_bm(&E, 1, 2, 25, 0));
    T("eor w1, w2, #0x100",        a64_eor_w_bm(&E, 1, 2, 24, 0));
    T("lsl w1, w2, #8",            a64_lsl_w_imm(&E, 1, 2, 8));
    T("lsl w1, w2, #24",           a64_lsl_w_imm(&E, 1, 2, 24));
    T("lsr w1, w2, #24",           a64_lsr_w_imm(&E, 1, 2, 24));
    T("asr w1, w2, #16",           a64_asr_w_imm(&E, 1, 2, 16));
    T("ubfx w1, w2, #8, #4",       a64_ubfx_w(&E, 1, 2, 8, 4));
    T("sbfx w1, w2, #4, #8",       a64_sbfx_w(&E, 1, 2, 4, 8));
    T("bfi w1, w2, #8, #8",        a64_bfi_w(&E, 1, 2, 8, 8));
    T("bfxil w1, w2, #16, #16",    a64_bfxil_w(&E, 1, 2, 16, 16));
    T("sxtb w1, w2",               a64_sxtb_w(&E, 1, 2));
    T("sxth w1, w2",               a64_sxth_w(&E, 1, 2));
    T("uxtb w1, w2",               a64_uxtb_w(&E, 1, 2));
    T("uxth w1, w2",               a64_uxth_w(&E, 1, 2));
    T("lsl w1, w2, w3",            a64_lslv_w(&E, 1, 2, 3));
    T("lsr w1, w2, w3",            a64_lsrv_w(&E, 1, 2, 3));
    T("asr w1, w2, w3",            a64_asrv_w(&E, 1, 2, 3));
    T("ror w1, w2, w3",            a64_rorv_w(&E, 1, 2, 3));
    T("rev16 w1, w2",              a64_rev16_w(&E, 1, 2));
    T("rev w1, w2",                a64_rev_w(&E, 1, 2));
    T("ror w1, w2, #8",            a64_ror_w_imm(&E, 1, 2, 8));
    T("mul w1, w2, w3",            a64_mul_w(&E, 1, 2, 3));
    T("smull x1, w2, w3",          a64_smull_x(&E, 1, 2, 3));
    T("umull x1, w2, w3",          a64_umull_x(&E, 1, 2, 3));
    T("udiv w1, w2, w3",           a64_udiv_w(&E, 1, 2, 3));
    T("sdiv w1, w2, w3",           a64_sdiv_w(&E, 1, 2, 3));
    T("cset w1, eq",               a64_cset_w(&E, 1, CC_EQ));
    T("cset w1, mi",               a64_cset_w(&E, 1, CC_MI));
    T("cset w1, cs",               a64_cset_w(&E, 1, CC_CS));
    T("cset w1, vs",               a64_cset_w(&E, 1, CC_VS));
    T("csel w1, w2, w3, lt",       a64_csel_w(&E, 1, 2, 3, CC_LT));
    T("mrs x1, nzcv",              a64_mrs_nzcv(&E, 1));
    T("b .+8",                     a64_b(&E, 8));
    T("b.ne .+16",                 a64_bcond(&E, CC_NE, 16));
    T("cbz w1, .+8",               a64_cbz_w(&E, 1, 8));
    T("cbnz w1, .-8",              a64_cbnz_w(&E, 1, -8));
    T("tbz w1, #7, .+12",          a64_tbz_w(&E, 1, 7, 12));
    T("tbnz w1, #8, .+12",         a64_tbnz_w(&E, 1, 8, 12));
    T("blr x16",                   a64_blr(&E, 16));
    T("br x17",                    a64_br(&E, 17));
    T("ret",                       a64_ret(&E));
    T("nop",                       a64_nop(&E));
    return 0;
}
